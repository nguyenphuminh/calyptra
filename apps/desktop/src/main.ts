/** The circuits' proving files, generated by `npm run setup`. */
const ARTIFACTS = fileURLToPath(new URL('../../../packages/framework/artifacts', import.meta.url));

async function main(argv: readonly string[]): Promise<void> {
  const config = loadConfig(argv);
  if (config.command === 'help') {
    process.stdout.write(`${USAGE}\n`);
    return;
  }
  const logger = createLogger(config.logLevel);
  const networks: NetworkConfig[] = [...BUILT_IN_NETWORKS];
  if (config.networkFile) networks.push(NetworkConfigSchema.parse(JSON.parse(await readFile(config.networkFile, 'utf8'))));
  const calyptra = new Calyptra({
    store: new FileStore(config.dataDir),
    artifacts: fileArtifacts(ARTIFACTS),
    createNode: createPeerNode,
    networks,
    libp2pRelays: config.libp2pRelays,
    relayers: config.relayers?.map((url) => new HttpRelayer(url)),
    rpcUrls: config.chainRpcs,
    rpcFallback: config.chainRpcFallback,
    maxFee: maxFeesOf(config, networks),
  });
  if (config.command === 'init') return init(config, calyptra);
  return start(config, calyptra, logger);
}

/** The highest relayer fee accepted per token id (0 = native coin, else the stablecoin of each network). */
function maxFeesOf(config: Config, networks: readonly NetworkConfig[]): Map<bigint, bigint> | undefined {
  const { native, stablecoin } = config.maxFee;
  if (native === undefined && stablecoin === undefined) return undefined;
  const fees = new Map<bigint, bigint>();
  if (native !== undefined) fees.set(0n, parseAmount('native', native));
  if (stablecoin !== undefined) for (const n of networks) fees.set(BigInt(n.stablecoin), parseAmount('stablecoin', stablecoin));
  return fees;
}

/** Creates the encrypted data folder from a phrase, a private key or a website export file. */
async function init(config: Config, calyptra: Calyptra): Promise<void> {
  const { wallet } = calyptra;
  if (await wallet.exists()) throw new AppError(409, 'ALREADY_INITIALIZED', `A wallet already exists in ${config.dataDir}`);
  if (config.init.source === 'import-file') {
    // The website's export file is the encrypted vault itself; its password stays the data password.
    const content = await readFile(config.init.importFile ?? '', 'utf8');
    await wallet.importFile(content, await readSecret('CALYPTRA_PASSWORD', 'Password of the export file: '));
  } else {
    const secret = await readSecret('CALYPTRA_SECRET', config.init.source === 'phrase' ? 'Recovery phrase: ' : 'Private key: ');
    const password = await readSecret('CALYPTRA_PASSWORD', 'New data password (8+ characters): ');
    if (!process.env.CALYPTRA_PASSWORD && (await readSecret('CALYPTRA_PASSWORD', 'Repeat the password: ')) !== password) {
      throw new AppError(400, 'PASSWORD_MISMATCH', 'The passwords do not match');
    }
    if (config.init.source === 'phrase') await wallet.createFromPhrase(secret, password);
    else await wallet.importPrivateKey(secret, password);
  }
  const accounts = wallet.accounts().map((a) => ({ id: a.id, label: a.label }));
  process.stdout.write(`${JSON.stringify({ dataDir: config.dataDir, accounts }, null, 2)}\n`);
  wallet.lock();
}

function listen(app: Express, port: number, host: string): Promise<Server> {
  return new Promise((resolve, reject) => {
    const server = app.listen(port, host);
    server.once('listening', () => resolve(server));
    server.once('error', reject);
  });
}

/** Runs the node until SIGINT/SIGTERM (or the shell's `exit`). */
async function start(config: Config, calyptra: Calyptra, logger: Logger): Promise<void> {
  const { wallet, keys } = calyptra;
  // Merchant mode (§11.5): the offer is checked before anything starts.
  const offer = config.merchant.enabled ? OfferSchema.parse(JSON.parse(await readFile(config.merchant.offerFile ?? '', 'utf8'))) : null;
  await wallet.unlock(await readSecret('CALYPTRA_PASSWORD', 'Data password: '));
  if (config.network) await wallet.setNetwork(config.network);
  const network = calyptra.network();

  let relayer: RelayerService | undefined;
  let relayerAccountId: string | undefined;
  if (config.relayer.enabled) {
    const wanted = (config.relayer.account ?? '').toLowerCase();
    const account = wallet.accounts().find((a) => a.id.toLowerCase() === wanted);
    if (!account) throw new AppError(404, 'UNKNOWN_ACCOUNT', `No account ${config.relayer.account} in this wallet`);
    if (account.id === wallet.activeAccount().id) throw new AppError(409, 'RELAYER_ACCOUNT', 'The relayer account cannot be the active account');
    if (account.used) throw new AppError(409, 'RELAYER_ACCOUNT', 'This account has made deposits; choose an unused account for relaying');
    relayerAccountId = account.id;
    relayer = new RelayerService(new ChainAdapter(network, { rpcUrls: calyptra.rpcUrls() }), {
      account: wallet.signer(account.id), // pays the gas of relayed transactions
      keys: await keys.poolKeys(account.id), // receives the fee notes
      fees: {
        [zeroAddress]: parseAmount('native', config.relayer.feeNative ?? ''),
        [network.stablecoin as Address]: parseAmount('stablecoin', config.relayer.feeStable ?? ''),
      },
    });
    if (!config.relayers) calyptra.configure({ relayers: [new DirectRelayer(relayer)] }); // relays its own transactions in-process
  }

  let relayNode: Libp2p | undefined;
  let rpc: { url: string; tokenFile: string } | null = null;
  let ready = false;
  let ticking = false;
  let interval: NodeJS.Timeout | undefined;
  const servers: Server[] = [];

  let stopping: Promise<void> | undefined;
  const shutdown = (): Promise<void> =>
    (stopping ??= (async () => {
      ready = false;
      clearInterval(interval);
      await Promise.all(servers.map((s) => new Promise<void>((resolve) => s.close(() => resolve()))));
      await relayNode?.stop();
      await calyptra.lock(); // stops the session, locks the wallet, forgets derived keys
      if (rpc) await rm(rpc.tokenFile, { force: true });
      logger.info({ module: 'node' }, 'stopped');
    })());

  try {
    if (config.libp2pRelay.enabled) {
      const { host, port, announce } = config.libp2pRelay;
      const first = wallet.accounts()[0]?.id;
      // The relay identity comes from the wallet's first account, unrelated to any channel identity,
      // so it is the same across restarts and on every machine that holds this wallet.
      const seed = hexToBytes(keccak256(concat([(await keys.poolKeys(first)).seed, stringToHex('libp2p-relay')])));
      relayNode = await createRelayNode({ listen: [`/ip4/${host}/tcp/${port}/ws`], announce, seed });
      const local = host === '0.0.0.0' ? '127.0.0.1' : host;
      const own = `/ip4/${local}/tcp/${port}/ws/p2p/${relayNode.peerId.toString()}`;
      if (!config.libp2pRelays) calyptra.configure({ libp2pRelays: [own] }); // reaches its own channel peers through itself
    }

    await calyptra.start();
    // Sells the offer as an AI chat on Qwen over the service protocol; subscribers open its card.
    const merchant = offer ? await createQwenMerchant(calyptra, offer, config.merchant.apiKey ?? '').start() : null;
    const relayerUrl = relayer ? `http://${config.relayer.host}:${config.relayer.port}` : null; // the listen URL, not a public one
    const libp2pRelay = (): string[] | null => relayNode?.getMultiaddrs().map(String) ?? null;
    const node = new NodeService(calyptra, {
      relayerAccountId,
      roles: () => ({ relayer: relayerUrl && relayerAccountId ? { url: relayerUrl, account: relayerAccountId } : null, libp2pRelay: libp2pRelay() }),
    });

    if (config.rpc.enabled) {
      const token = randomBytes(32).toString('hex'); // new at every start, never stored in the data folder
      servers.push(await listen(createRpcApp({ node, token, logger, ready: () => ready }), config.rpc.port, '127.0.0.1'));
      const url = `http://127.0.0.1:${config.rpc.port}`;
      await mkdir(dirname(config.rpc.tokenFile), { recursive: true, mode: 0o700 });
      await writeFile(config.rpc.tokenFile, JSON.stringify({ url, token }), { mode: 0o600 });
      rpc = { url, tokenFile: config.rpc.tokenFile };
    }
    if (relayer) {
      const hyperRpc = hyperRpcOf(config, network, logger);
      servers.push(await listen(createRelayerApp({ relayer, logger, hyperRpc }), config.relayer.port, config.relayer.host));
    }

    interval = setInterval(() => {
      if (ticking) return; // the previous tick is still running
      ticking = true;
      calyptra
        .tick()
        .then((problems) => {
          for (const p of problems) logger.warn({ module: 'node', channel: p.channelId, err: p.error }, 'channel needs attention');
        })
        .catch((err: unknown) => logger.warn({ module: 'node', err }, 'background sync failed'))
        .finally(() => {
          ticking = false;
        });
    }, config.tickSeconds * 1000);

    for (const signal of ['SIGINT', 'SIGTERM'] as const) {
      process.once(signal, () => {
        void shutdown().then(() => process.exit(0));
      });
    }

    ready = true;
    const summary = { account: wallet.activeAccount().id, network: network.id, rpc, relayer: relayerUrl, libp2pRelay: libp2pRelay(), merchant };
    process.stdout.write(`calyptra ready ${JSON.stringify(summary)}\n`); // the machine-readable readiness line
    logger.info({ module: 'node', ...summary }, 'started');

    if (config.shell && process.stdin.isTTY) {
      await new ShellService(node).run(process.stdin, process.stdout);
      await shutdown();
      process.exit(0);
    }
  } catch (err) {
    await shutdown().catch(() => undefined); // nothing may keep a failed start alive
    throw err;
  }
}

/** The relay host's wallet-sync proxy (§11.3): on only with an Envio token and deployed contracts. */
function hyperRpcOf(config: Config, network: NetworkConfig, logger: Logger): HyperRpcService | undefined {
  if (!config.envioToken || !network.contracts) return undefined;
  logger.info({ module: 'hyperrpc' }, 'wallet-sync proxy enabled at POST /hyperrpc');
  return createHyperRpcService({
    upstreamUrl: envioHyperRpcUrl(network.chainId, config.envioToken),
    contracts: [network.contracts.pool, network.contracts.disputes],
  });
}

main(process.argv.slice(2)).catch((err: unknown) => {
  process.stderr.write(`${formatError(err)}\n`);
  process.exitCode = 1;
});
